"""Deterministic Makefile rendering from a root `x.toml`.

By default the Makefile is a thin wrapper: each target runs the
command of the same name through the launcher named by `X`, so
`make build` and `x build` are one run. A command's own `recipe`, or
a `header` that defines `X` differently, changes that for the
repository that wrote it.
"""

from __future__ import annotations

import os
from pathlib import Path
import re

from x.config import CommandConfig, MakefileConfig, RootConfig
from x.model import SpecError


PACKAGE = "@tryc.ai/x"
BANNER = "# Generated by x from x.toml. Do not edit by hand."
_BANNER_PREFIX = "# Generated by x "
_TARGET = re.compile(r"^[A-Za-z0-9_.+-]+$")


def default_launcher(version: str) -> str:
    return "npx --yes " + PACKAGE + "@" + version


def default_header(make: MakefileConfig, version: str) -> tuple[str, ...]:
    launcher = make.launcher
    if launcher is None:
        launcher = default_launcher(version)
    lines = ["X := " + launcher, "ARGS ?="]
    if make.default is not None:
        lines.append(".DEFAULT_GOAL := " + make.default)
    return tuple(lines)


def _rule(target: str, command: CommandConfig, forward_args: bool) -> str:
    own = target == command.name
    lines = [".PHONY: " + target]
    if own:
        lines.extend(command.make.prelude)
    lines.append(target + ":")
    if command.make.recipe and own:
        for line in command.make.recipe:
            lines.append("\t" + line)
    else:
        recipe = "\t@$(X) " + target
        if forward_args:
            recipe += " $(ARGS)"
        lines.append(recipe)
    return "\n".join(lines)


def _targets(root: RootConfig, make: MakefileConfig) -> list[tuple[str, CommandConfig]]:
    selected: list[tuple[str, CommandConfig]] = []
    seen: dict[str, str] = {}
    for command in root.commands:
        if not command.make.enabled:
            continue
        names = [command.name]
        with_aliases = make.aliases
        if command.make.aliases is not None:
            with_aliases = command.make.aliases
        if with_aliases:
            names.extend(command.aliases)
        for name in names:
            if not _TARGET.match(name):
                raise SpecError(
                    "a command named '"
                    + name
                    + "' cannot be a Make target; rename it or set make = false"
                )
            if name in seen:
                raise SpecError(
                    "duplicate Make target '"
                    + name
                    + "': "
                    + seen[name]
                    + ", "
                    + command.name
                )
            seen[name] = command.name
            selected.append((name, command))
    if make.order == "alpha":
        selected.sort(key=lambda entry: entry[0])
    return selected


def render_makefile(root: RootConfig) -> str:
    """Return the Makefile text for a root config with a `[make]` table."""
    make = root.make
    if make is None:
        raise SpecError("x.toml has no [make] table")

    header = make.header
    if header is None:
        header = default_header(make, root.version)

    blocks = [BANNER, "\n".join(header)]
    for target, command in _targets(root, make):
        forward_args = make.args
        if command.make.args is not None:
            forward_args = command.make.args
        blocks.append(_rule(target, command, forward_args))
        if command.make.after and target == command.name:
            blocks.append("\n".join(command.make.after))
    return "\n\n".join(blocks) + "\n"


def makefile_path(root: RootConfig) -> Path:
    make = root.make
    name = "Makefile"
    if make is not None:
        name = make.path
    return root.directory / name


def is_generated(path: Path) -> bool:
    """True when `path` is absent or was written by this generator."""
    try:
        with path.open("rb") as stream:
            first = stream.readline()
    except FileNotFoundError:
        return True
    except OSError:
        # A folder, or a file that cannot be read: not ours to replace.
        return False
    return first.decode("utf-8", "replace").startswith(_BANNER_PREFIX)


def check_makefile(path: Path, expected: str) -> bool:
    try:
        actual = path.read_bytes()
    except OSError:
        return False
    return actual == expected.encode("utf-8")


def write_makefile(path: Path, contents: str) -> None:
    temporary = path.with_name(path.name + ".x-tmp")
    temporary.write_bytes(contents.encode("utf-8"))
    try:
        os.replace(temporary, path)
    except OSError:
        # Nothing was replaced, so leave nothing behind either.
        temporary.unlink(missing_ok=True)
        raise
